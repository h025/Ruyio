import CryptoKit
import Foundation

/// Capture rules. Type lists follow Maccy (MIT, © Alex Rodionov) and http://nspasteboard.org;
/// see THIRD_PARTY_NOTICES.md.
public enum PasteboardRules {
    public static let text = "public.utf8-plain-text"
    public static let rtf = "public.rtf"
    public static let rtfd = "com.apple.flat-rtfd"
    public static let html = "public.html"
    public static let png = "public.png"
    public static let tiff = "public.tiff"
    public static let jpeg = "public.jpeg"
    public static let heic = "public.heic"
    public static let url = "public.url"
    public static let fileURL = "public.file-url"

    /// Ruyio's own write-back marker; captures carrying it are ignored (self-write suppression).
    public static let originMarker = "app.ruyio.origin"
    public static let sourceMarker = "org.nspasteboard.source"

    public static let supported: [String] = [text, rtf, rtfd, html, png, tiff, jpeg, heic, url, fileURL]
    public static let imageTypes: Set<String> = [png, tiff, jpeg, heic]

    /// nspasteboard.org markers plus password-manager conventions: never record (PRD §8.2).
    public static let sensitiveMarkers: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.agilebits.onepassword",
        "net.antelle.keeweb",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    /// Volatile metadata that differs between otherwise identical copies; ignored when de-duplicating.
    public static let volatileTypes: Set<String> = [
        "x.nspasteboard.ModifiedType", originMarker, sourceMarker,
        "com.apple.linkpresentation.metadata", "com.apple.WebKit.custom-pasteboard-data",
        "org.chromium.web-custom-data", "org.chromium.source-url", "org.chromium.internal.source-rfh-token",
        "com.apple.notes.richtext",
    ]

    /// Huge or non-reconstructible types we do not persist (Maccy: web archives, dyn.*, Office OLE source).
    public static func isPersistable(_ type: String) -> Bool {
        if type == "com.apple.webarchive" || type == "Apple Web Archive pasteboard type" { return false }
        if type.hasPrefix("dyn.") || type.hasPrefix("com.microsoft.ole.source.") { return false }
        return supported.contains(type)
    }

    public static func isSensitive(types: Set<String>) -> Bool {
        !types.isDisjoint(with: sensitiveMarkers)
    }

    public static func isOwnWrite(types: Set<String>) -> Bool {
        types.contains(originMarker)
    }

    /// Item order, type and payload digest, ignoring volatile metadata (plan §12.2; Maccy "supersedes").
    public static func fingerprint(items: [[String: Data]]) -> String {
        var hasher = SHA256()
        for (index, item) in items.enumerated() {
            hasher.update(data: Data("item:\(index);".utf8))
            for type in item.keys.sorted() where !volatileTypes.contains(type) {
                guard let data = item[type] else { continue }
                hasher.update(data: Data("\(type)=".utf8))
                hasher.update(data: Data(SHA256.hash(data: data)))
            }
        }
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }

    public enum Kind: String, Codable, Sendable, CaseIterable {
        case text, richText, image, url, file
        public var filter: String {
            switch self {
            case .text, .richText: return "text"
            case .image: return "image"
            case .url: return "url"
            case .file: return "file"
            }
        }
    }

    /// Primary kind used for filtering, icons and Finder context (PRD §8.1).
    public static func kind(of items: [[String: Data]]) -> Kind? {
        let types = Set(items.flatMap(\.keys))
        if types.contains(fileURL) { return .file }
        if !types.isDisjoint(with: imageTypes) && !types.contains(text) { return .image }
        if types.contains(url) { return .url }
        if let textData = items.first?[text], let string = String(data: textData, encoding: .utf8), isSingleWebURL(string) { return .url }
        if !types.isDisjoint(with: [rtf, rtfd, html]) { return .richText }
        if types.contains(text) { return .text }
        if !types.isDisjoint(with: imageTypes) { return .image }
        return nil
    }

    public static func isSingleWebURL(_ string: String) -> Bool {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.contains(where: \.isWhitespace), trimmed.count < 4096,
              let components = URLComponents(string: trimmed), let scheme = components.scheme?.lowercased() else { return false }
        return (scheme == "http" || scheme == "https") && components.host?.isEmpty == false
    }

    /// Empty plain text with no rich content produces no record (Maccy).
    public static func isEffectivelyEmpty(_ item: [String: Data]) -> Bool {
        let hasNonText = item.keys.contains { $0 != text && supported.contains($0) }
        guard !hasNonText else { return false }
        guard let data = item[text], let string = String(data: data, encoding: .utf8) else { return true }
        return string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }
}

/// Limits from plan §16.
public enum CaptureLimits {
    public static let maxTextBytes = 4 << 20
    public static let maxImageBytes = 32 << 20
    public static let maxRecordBytes = 64 << 20
    public static let maxImagePixels = 40_000_000
    public static let pollInterval: TimeInterval = 0.35
    public static let defaultRetentionDays = 30
    public static let defaultMaxRecords = 5_000
    public static let undoWindow: TimeInterval = 6
}
